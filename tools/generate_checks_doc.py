"""Writes docs/checks.md from the registry, and verifies it has not drifted.

The SARIF output points every finding's help link at an anchor in this file, so
a check whose section is missing is a link to nothing from the security tab. A
hand written table would be correct on the day it was written.

With --check it compares rather than writes, which is what CI runs. A generated
file that is only regenerated when someone remembers is a hand written file
with extra steps.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from drg.checks import registry  # noqa: E402

TARGET = ROOT / "docs" / "checks.md"
METRICS = ROOT / "docs" / "metrics.json"

PREAMBLE = """\
# Checks

Generated by `tools/generate_checks_doc.py` from the check registry. Edit the
`rationale` on the check, not this file.

Every default severity below was set from how often the check fires on the
pinned public corpus of {rules} Sigma rules, not from how serious the finding
sounds. A check that fails the build on a quarter of a team's existing rules is
a check that gets switched off in its first week, so a high firing rate argues
for a warning default even where the finding is worth making. The rates are
measured, and `benchmark/run_benchmark.py` reproduces them.

Two findings cannot be configured: a file that does not parse, and a file that
parses and is not a Sigma rule. Neither can be assessed, and neither will load
in a backend.

| check | default | scope | fires on corpus |
| --- | --- | --- | --- |
"""


def rates() -> dict[str, dict]:
    if not METRICS.is_file():
        return {}
    return json.loads(METRICS.read_text(encoding="utf-8")).get("checks", {})


def render() -> str:
    specs = registry()
    measured = rates()
    total = 0
    if METRICS.is_file():
        total = json.loads(METRICS.read_text(encoding="utf-8")).get("rules_loaded", 0)

    lines = [PREAMBLE.format(rules=f"{total:,}" if total else "public").rstrip("\n")]
    for check_id, entry in specs.items():
        seen = measured.get(check_id)
        fired = f"{seen['fired']} ({seen['rate_percent']}%)" if seen else "not measured"
        lines.append(f"| [`{check_id}`](#{check_id}) | {entry.default.value} | {entry.scope} | {fired} |")
    lines.append("")

    for check_id, entry in specs.items():
        seen = measured.get(check_id)
        lines.append(f"## {check_id}")
        lines.append("")
        lines.append(f"**{entry.summary}**")
        lines.append("")
        lines.append(entry.rationale)
        lines.append("")
        lines.append(f"- Default severity: `{entry.default.value}`")
        lines.append(f"- Scope: {entry.scope}")
        if seen:
            lines.append(f"- Fires on {seen['fired']} of the corpus ({seen['rate_percent']}%)")
        if entry.options:
            rendered = ", ".join(f"`{name}` (default `{value}`)" for name, value in entry.options.items())
            lines.append(f"- Options: {rendered}")
        if check_id in {"rule-unparseable", "rule-invalid", "suppression-without-reason", "suppression-unknown-check"}:
            lines.append("- Not configurable")
        lines.append("")

    lines.append("## Turning a check off")
    lines.append("")
    lines.append("In `.detection-rule-gate.yml`:")
    lines.append("")
    lines.append("```yaml")
    lines.append("checks:")
    lines.append("  missing-falsepositives: off")
    lines.append("  attack-technique-missing: error")
    lines.append("```")
    lines.append("")
    lines.append("For one rule, in the rule file, with a reason that is not optional:")
    lines.append("")
    lines.append("```yaml")
    lines.append("# drg:ignore unbounded-selection reason: allowlist detection, breadth is the design")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    args = parser.parse_args(argv)

    rendered = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != rendered:
            print(f"{TARGET} is out of date. Run: python tools/generate_checks_doc.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches the registry")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET} ({len(registry())} checks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
